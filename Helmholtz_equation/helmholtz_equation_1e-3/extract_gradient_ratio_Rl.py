#!/usr/bin/env python3

"""
Extract layer-wise gradient-scale ratios:

    R_l = ||g_reg^(l)|| / (||g_data^(l)|| + eps)

and

    log10(R_l)

The script is designed to work directly with the gradient-history CSVs
used in the Burgers and Helmholtz examples, and it also accepts several
common alternative column names used in MSE/regularizer diagnostics.

Typical accepted columns
------------------------

Data/MSE gradient norm:
    data_grad_norm
    mse_grad_norm
    mse_gradient_norm
    gradient_norm_mse

Regularization/PDE gradient norm:
    regularization_grad_norm
    pde_grad_norm
    reg_grad_norm
    regularizer_grad_norm
    gradient_norm_reg
    gradient_norm_regularization

Scaled regularization norm (optional):
    scaled_regularization_grad_norm
    scaled_pde_grad_norm
    scaled_reg_grad_norm

Layer:
    layer
    layer_index
    layer_name

Epoch:
    epoch

Usage
-----

Single CSV:
    python extract_gradient_ratio_Rl.py path/to/layer_gradient_scales.csv

Whole project folder:
    python extract_gradient_ratio_Rl.py ~/Alternative_trainings

If no path is supplied, the script searches recursively from the folder
where this script is located.

Outputs
-------

For every compatible input CSV:
    *_with_Rl.csv
    *_Rl_summary_by_layer.csv
    *_Rl_vs_epoch.png
    *_log10_Rl_vs_epoch.png

Additionally, when multiple compatible CSVs are found:
    combined_Rl_summary.csv
    combined_log10_Rl_boxplot.png
"""

from pathlib import Path
import argparse

import numpy as np
import pandas as pd
import matplotlib.pyplot as plt


EPS = 1e-20


DATA_NORM_CANDIDATES = [
    "data_grad_norm",
    "mse_grad_norm",
    "mse_gradient_norm",
    "gradient_norm_mse",
    "data_gradient_norm",
    "supervised_grad_norm",
]

REG_NORM_CANDIDATES = [
    "regularization_grad_norm",
    "pde_grad_norm",
    "reg_grad_norm",
    "regularizer_grad_norm",
    "gradient_norm_reg",
    "gradient_norm_regularization",
    "physics_grad_norm",
    "mass_grad_norm",
]

SCALED_REG_NORM_CANDIDATES = [
    "scaled_regularization_grad_norm",
    "scaled_pde_grad_norm",
    "scaled_reg_grad_norm",
    "scaled_regularizer_grad_norm",
    "scaled_physics_grad_norm",
    "scaled_mass_grad_norm",
]

LAYER_CANDIDATES = [
    "layer",
    "layer_index",
    "layer_name",
]

EPOCH_CANDIDATES = [
    "epoch",
    "Epoch",
]


def find_column(df, candidates):
    lower_map = {
        str(col).lower(): col
        for col in df.columns
    }

    for candidate in candidates:
        if candidate.lower() in lower_map:
            return lower_map[candidate.lower()]

    return None


def identify_columns(df):
    data_col = find_column(
        df,
        DATA_NORM_CANDIDATES,
    )

    reg_col = find_column(
        df,
        REG_NORM_CANDIDATES,
    )

    scaled_reg_col = find_column(
        df,
        SCALED_REG_NORM_CANDIDATES,
    )

    layer_col = find_column(
        df,
        LAYER_CANDIDATES,
    )

    epoch_col = find_column(
        df,
        EPOCH_CANDIDATES,
    )

    return {
        "data": data_col,
        "reg": reg_col,
        "scaled_reg": scaled_reg_col,
        "layer": layer_col,
        "epoch": epoch_col,
    }


def compatible_csv(path):
    try:
        df = pd.read_csv(
            path,
            nrows=10,
        )
    except Exception:
        return False

    columns = identify_columns(df)

    return (
        columns["data"] is not None
        and columns["reg"] is not None
    )


def discover_csvs(path):
    path = path.expanduser().resolve()

    if path.is_file():
        if path.suffix.lower() != ".csv":
            raise ValueError(
                f"Input file is not a CSV: {path}"
            )

        if not compatible_csv(path):
            raise ValueError(
                "The CSV does not contain recognizable "
                "data/MSE and regularization gradient norm columns.\n"
                f"Columns found: {list(pd.read_csv(path, nrows=1).columns)}"
            )

        return [path]

    candidates = []

    for csv_path in path.rglob("*.csv"):

        # Do not re-read files generated by this script.
        if (
            "_with_Rl" in csv_path.stem
            or "_Rl_summary" in csv_path.stem
            or csv_path.name == "combined_Rl_summary.csv"
        ):
            continue

        if compatible_csv(csv_path):
            candidates.append(
                csv_path
            )

    return sorted(candidates)


def safe_ratio(numerator, denominator):
    numerator = np.asarray(
        numerator,
        dtype=float,
    )

    denominator = np.asarray(
        denominator,
        dtype=float,
    )

    return numerator / (
        np.abs(denominator)
        + EPS
    )


def label_from_path(path, root):
    try:
        relative = path.relative_to(
            root
        )
    except ValueError:
        relative = path

    parent = str(
        relative.parent
    )

    if parent == ".":
        return path.stem

    return (
        parent.replace("\\", "/")
        + "/"
        + path.stem
    )


def process_csv(path, root):
    df = pd.read_csv(
        path
    )

    columns = identify_columns(
        df
    )

    data_col = columns["data"]
    reg_col = columns["reg"]
    scaled_reg_col = columns[
        "scaled_reg"
    ]
    layer_col = columns["layer"]
    epoch_col = columns["epoch"]

    result = df.copy()

    result[
        "R_l_raw"
    ] = safe_ratio(
        result[reg_col],
        result[data_col],
    )

    result[
        "log10_R_l_raw"
    ] = np.log10(
        np.maximum(
            result["R_l_raw"],
            EPS,
        )
    )

    if scaled_reg_col is not None:

        result[
            "R_l_scaled"
        ] = safe_ratio(
            result[scaled_reg_col],
            result[data_col],
        )

        result[
            "log10_R_l_scaled"
        ] = np.log10(
            np.maximum(
                result["R_l_scaled"],
                EPS,
            )
        )

    if layer_col is None:
        result[
            "_layer_for_analysis"
        ] = "all"

        analysis_layer_col = (
            "_layer_for_analysis"
        )
    else:
        analysis_layer_col = (
            layer_col
        )

    output_csv = (
        path.parent
        / f"{path.stem}_with_Rl.csv"
    )

    result.to_csv(
        output_csv,
        index=False,
    )

    grouped = (
        result.groupby(
            analysis_layer_col,
            dropna=False,
        )
        .agg(
            R_l_raw_mean=(
                "R_l_raw",
                "mean",
            ),
            R_l_raw_median=(
                "R_l_raw",
                "median",
            ),
            R_l_raw_min=(
                "R_l_raw",
                "min",
            ),
            R_l_raw_max=(
                "R_l_raw",
                "max",
            ),
            log10_R_l_raw_mean=(
                "log10_R_l_raw",
                "mean",
            ),
            log10_R_l_raw_std=(
                "log10_R_l_raw",
                "std",
            ),
        )
        .reset_index()
    )

    if "R_l_scaled" in result.columns:

        scaled_grouped = (
            result.groupby(
                analysis_layer_col,
                dropna=False,
            )
            .agg(
                R_l_scaled_mean=(
                    "R_l_scaled",
                    "mean",
                ),
                R_l_scaled_median=(
                    "R_l_scaled",
                    "median",
                ),
                R_l_scaled_min=(
                    "R_l_scaled",
                    "min",
                ),
                R_l_scaled_max=(
                    "R_l_scaled",
                    "max",
                ),
                log10_R_l_scaled_mean=(
                    "log10_R_l_scaled",
                    "mean",
                ),
                log10_R_l_scaled_std=(
                    "log10_R_l_scaled",
                    "std",
                ),
            )
            .reset_index()
        )

        grouped = grouped.merge(
            scaled_grouped,
            on=analysis_layer_col,
            how="left",
        )

    summary_csv = (
        path.parent
        / f"{path.stem}_Rl_summary_by_layer.csv"
    )

    grouped.to_csv(
        summary_csv,
        index=False,
    )

    dataset_label = label_from_path(
        path,
        root,
    )

    if (
        epoch_col is not None
        and layer_col is not None
    ):
        plot_ratio_vs_epoch(
            result,
            epoch_col,
            layer_col,
            dataset_label,
            path.parent
            / f"{path.stem}_Rl_vs_epoch.png",
            log_scale=False,
        )

        plot_ratio_vs_epoch(
            result,
            epoch_col,
            layer_col,
            dataset_label,
            path.parent
            / f"{path.stem}_log10_Rl_vs_epoch.png",
            log_scale=True,
        )

    summary_for_combined = grouped.copy()

    summary_for_combined.insert(
        0,
        "source",
        dataset_label,
    )

    print(
        f"\nProcessed: {path}"
    )

    print(
        f"  data gradient column: {data_col}"
    )

    print(
        f"  regularization gradient column: {reg_col}"
    )

    if scaled_reg_col:
        print(
            f"  scaled regularization column: {scaled_reg_col}"
        )

    print(
        f"  output: {output_csv.name}"
    )

    return (
        result,
        summary_for_combined,
        dataset_label,
    )


def plot_ratio_vs_epoch(
    df,
    epoch_col,
    layer_col,
    title_label,
    output_path,
    log_scale,
):
    fig, ax = plt.subplots(
        figsize=(9, 5.5)
    )

    value_col = (
        "log10_R_l_raw"
        if log_scale
        else "R_l_raw"
    )

    for layer in sorted(
        df[layer_col]
        .dropna()
        .unique(),
        key=lambda x: str(x),
    ):

        subset = df[
            df[layer_col] == layer
        ].sort_values(
            epoch_col
        )

        ax.plot(
            subset[epoch_col],
            subset[value_col],
            label=f"Layer {layer}",
            linewidth=1.4,
        )

    ax.set_xlabel(
        "Epoch"
    )

    if log_scale:

        ax.set_ylabel(
            r"$\log_{10}(R_l)$"
        )

        ax.axhline(
            0.0,
            linestyle="--",
            linewidth=1.0,
        )

    else:

        ax.set_ylabel(
            r"$R_l = ||g_{reg}^{(l)}|| / ||g_{data}^{(l)}||$"
        )

        ax.set_yscale(
            "log"
        )

        ax.axhline(
            1.0,
            linestyle="--",
            linewidth=1.0,
        )

    #ax.set_title(
        #f"Layer-wise gradient ratio\n{title_label}"
    #)

    ax.grid(
        True,
        alpha=0.3,
    )

    ax.legend()

    fig.tight_layout()

    fig.savefig(
        output_path,
        dpi=300,
    )

    plt.close(
        fig
    )


def combined_boxplot(
    processed_results,
    output_path,
):
    if len(
        processed_results
    ) < 2:
        return

    data = []
    labels = []

    for result, _, label in processed_results:

        values = (
            result["log10_R_l_raw"]
            .replace(
                [np.inf, -np.inf],
                np.nan,
            )
            .dropna()
            .to_numpy()
        )

        if len(values) == 0:
            continue

        data.append(
            values
        )

        labels.append(
            label
        )

    if len(data) < 2:
        return

    fig, ax = plt.subplots(
        figsize=(
            max(
                8,
                1.8 * len(data),
            ),
            5.5,
        )
    )

    ax.boxplot(
        data,
        labels=labels,
        showfliers=False,
    )

    ax.axhline(
        0.0,
        linestyle="--",
        linewidth=1.0,
    )

    ax.set_ylabel(
        r"$\log_{10}(R_l)$"
    )

    ax.set_title(
        "Gradient-scale imbalance across cases"
    )

    ax.tick_params(
        axis="x",
        rotation=30,
    )

    ax.grid(
        True,
        axis="y",
        alpha=0.3,
    )

    fig.tight_layout()

    fig.savefig(
        output_path,
        dpi=300,
    )

    plt.close(
        fig
    )


def main():
    parser = argparse.ArgumentParser(
        description=(
            "Extract layer-wise gradient ratio "
            "R_l = ||g_reg|| / ||g_data||."
        )
    )

    parser.add_argument(
        "path",
        nargs="?",
        default=None,
        help=(
            "CSV file or project directory. "
            "Default: directory containing this script."
        ),
    )

    args = parser.parse_args()

    script_dir = (
        Path(__file__)
        .resolve()
        .parent
    )

    if args.path is None:
        input_path = script_dir
    else:
        input_path = Path(
            args.path
        ).expanduser()

    root = (
        input_path.resolve()
        if input_path.is_dir()
        else input_path.resolve().parent
    )

    csvs = discover_csvs(
        input_path
    )

    if not csvs:
        raise FileNotFoundError(
            "No compatible gradient-history CSV files were found.\n"
            "The CSV must contain a recognizable data/MSE gradient norm "
            "column and a regularization/PDE gradient norm column."
        )

    print(
        f"Found {len(csvs)} compatible CSV file(s)."
    )

    processed_results = []
    combined_summaries = []

    for csv_path in csvs:

        result, summary, label = process_csv(
            csv_path,
            root,
        )

        processed_results.append(
            (
                result,
                summary,
                label,
            )
        )

        combined_summaries.append(
            summary
        )

    if combined_summaries:

        combined = pd.concat(
            combined_summaries,
            ignore_index=True,
        )

        combined_path = (
            root
            / "combined_Rl_summary.csv"
        )

        combined.to_csv(
            combined_path,
            index=False,
        )

        print(
            f"\nCombined summary: {combined_path}"
        )

    combined_boxplot(
        processed_results,
        root
        / "combined_log10_Rl_boxplot.png",
    )

    print(
        "\nInterpretation:"
    )

    print(
        "  R_l = 1      -> equal gradient norms"
    )

    print(
        "  R_l > 1      -> regularization gradient is larger"
    )

    print(
        "  R_l < 1      -> data/MSE gradient is larger"
    )

    print(
        "  log10(R_l)=0 -> equal norms"
    )

    print(
        "  log10(R_l)=3 -> regularization is 10^3 times larger"
    )

    print(
        "  log10(R_l)=-3 -> regularization is 10^3 times smaller"
    )


if __name__ == "__main__":
    main()
